-- program duplicates_and_discovery
CREATE ROLE w5p_a;
CREATE ROLE w5p_b;
CREATE TABLE t(x INT, y INT);
GRANT SELECT ON t, t TO w5p_a, w5p_a;
GRANT USAGE ON SCHEMA public, public TO w5p_a;
SELECT relacl FROM pg_class WHERE relname = 't';
SELECT nspacl FROM pg_namespace WHERE nspname = 'public';
SELECT grantor, grantee, privilege_type::text, is_grantable::text FROM information_schema.table_privileges WHERE table_name = 't' ORDER BY grantee, privilege_type;
GRANT UPDATE (y) ON t TO w5p_b;
SET ROLE w5p_b;
SELECT table_name FROM information_schema.tables WHERE table_name = 't';
RESET ROLE;
REVOKE USAGE ON SCHEMA public FROM w5p_a;
DROP TABLE t;
DROP ROLE w5p_a, w5p_b;
