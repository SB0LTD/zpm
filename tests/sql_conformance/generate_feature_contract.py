#!/usr/bin/env python3
"""Generate the allocator-free in-process feature-probe contract.

Reads the probe programs (features/*.sql), their native PostgreSQL recording
(feature_probes_oracle.json) and, when present, the committed scoreboard
(postgres18_feature_status.json). Writes tests/test_sql_features.sig, which runs
every probe through ZPM's PostgreSQL wire session over a store connection on a
fresh database, reduces each response to the canonical form of
feature_probes.py and prints one JSON line per probe.

The contract exits nonzero only when a probe that the committed scoreboard
records as passing fails (a regression). Probes that start passing are
reported as improvements; run feature_status.py to fold them in.
"""
import argparse
import json
from pathlib import Path

import feature_probes as fp

OUTPUT = fp.ROOT.parent / 'test_sql_features.sig'


def literal(value: str) -> str:
    return '"' + ''.join(chr(b) if 32 <= b < 127 and b not in (34, 92) else f'\\x{b:02x}'
                         for b in value.encode('utf8')) + '"'


PRELUDE = r'''//! GENERATED by tests/sql_conformance/generate_feature_contract.py from
//! tests/sql_conformance/features/*.sql, feature_probes_oracle.json (native
//! PostgreSQL 18.7) and postgres18_feature_status.json. Do not edit by hand.
//!
//! SQL-standard feature probes (B11 wave 4, features lane). Every probe runs on
//! a fresh database through the PostgreSQL wire session over a store
//! connection, one simple Query per statement, continuing after errors. Each
//! response is reduced to canonical bytes (see feature_probes.py): message
//! order, RowDescription name/type/typlen/typmod, command tags, SQLSTATEs,
//! ReadyForQuery status and DataRow text. Allocated type OIDs (>= 16384) are
//! compared by catalog identity, read from pg_type in the same session.
//! A probe that the committed scoreboard records as passing must still pass.
const std = @import("std");
const sql = @import("sql");
const pg = @import("postgres");
const DB = sql.Database(.{ .tables = 16, .columns = 16, .rows_per_table = 64, .name_bytes = 63, .text_bytes = 512,
    .nulls_first_ascending = false, .integer_bits = 32, .expr_nodes = 2048, .work_rows = 256, .result_rows = 128,
    .relations = 8, .subqueries = 32, .ctes = 8, .schemas = 8, .transactions = 4, .predicates = 32,
    .routines = 32, .triggers = 16, .rules = 8, .catalog_objects = 128, .cursors = 8, .cursor_rows = 128 });
const Store = @import("db_store").Store(DB);
const Session = pg.Session(Store.Connection);

const Statement = struct { source: []const u8, head: []const u8, rows: []const []const u8 };
const Probe = struct { id: []const u8, ordered: bool, closed: bool, statements: []const Statement };

var store: Store = .{};
var conn: Store.Connection = undefined;
var wire: Session = .{};
var output: [Session.responseCapacity()]u8 = undefined;
var packet: [16384]u8 = undefined;
var raw_head: [8192]u8 = undefined;
var head: [8192]u8 = undefined;
var head_len: usize = 0;
var rows_text: [65536]u8 = undefined;
var row_ends: [512]usize = undefined;
var row_count: usize = 0;
var used: [512]bool = undefined;
var line_buffer: [4096]u8 = undefined;

const Out = struct {
    buf: []u8,
    len: usize = 0,
    fn put(self: *Out, bytes: []const u8) !void {
        if (bytes.len > self.buf.len - self.len) return error.CanonicalCapacity;
        @memcpy(self.buf[self.len..][0..bytes.len], bytes);
        self.len += bytes.len;
    }
    fn byte(self: *Out, value: u8) !void {
        if (self.len == self.buf.len) return error.CanonicalCapacity;
        self.buf[self.len] = value;
        self.len += 1;
    }
    fn int(self: *Out, value: i64) !void {
        var digits: [24]u8 = undefined;
        try self.put(try std.fmt.bufPrint(&digits, "{d}", .{value}));
    }
    fn esc(self: *Out, bytes: []const u8) !void {
        const hex = "0123456789abcdef";
        for (bytes) |b| switch (b) {
            '\\', '|', ',', '/', ';', '#' => {
                try self.byte('\\');
                try self.byte(b);
            },
            else => if (b < 0x20 or b == 0x7f) {
                try self.put("\\x");
                try self.byte(hex[b >> 4]);
                try self.byte(hex[b & 15]);
            } else try self.byte(b),
        };
    }
    /// JSON string body; UTF-8 passes through, cut at a character boundary.
    fn json(self: *Out, bytes: []const u8, limit: usize) !void {
        const hex = "0123456789abcdef";
        var end = @min(bytes.len, limit);
        while (end < bytes.len and end > 0 and bytes[end] & 0xc0 == 0x80) end -= 1;
        for (bytes[0..end]) |b| switch (b) {
            '"', '\\' => {
                try self.byte('\\');
                try self.byte(b);
            },
            else => if (b < 0x20 or b == 0x7f) {
                try self.put("\\u00");
                try self.byte(hex[b >> 4]);
                try self.byte(hex[b & 15]);
            } else try self.byte(b),
        };
    }
};

fn be32(bytes: []const u8) u32 {
    return (@as(u32, bytes[0]) << 24) | (@as(u32, bytes[1]) << 16) | (@as(u32, bytes[2]) << 8) | bytes[3];
}

fn be16(bytes: []const u8) u16 {
    return (@as(u16, bytes[0]) << 8) | bytes[1];
}

fn put32(bytes: []u8, value: u32) void {
    bytes[0] = @truncate(value >> 24);
    bytes[1] = @truncate(value >> 16);
    bytes[2] = @truncate(value >> 8);
    bytes[3] = @truncate(value);
}

fn same(a: []const u8, b: []const u8) bool {
    return std.mem.eql(u8, a, b);
}

fn startup() !void {
    var at: usize = 4;
    put32(packet[at..], 196608);
    at += 4;
    for ([_][]const u8{ "user", "ramsql", "database", "w4_features_probe", "client_encoding", "UTF8", "TimeZone", "UTC" }) |item| {
        @memcpy(packet[at..][0..item.len], item);
        at += item.len;
        packet[at] = 0;
        at += 1;
    }
    packet[at] = 0;
    at += 1;
    put32(packet[0..4], @intCast(at));
    const reply = try wire.handle(&conn, packet[0..at], &output);
    if (reply.consumed != at or !wire.startup or reply.close) return error.StartupFailed;
}

fn query(source: []const u8) ![]const u8 {
    if (source.len + 6 > packet.len) return error.StatementTooLong;
    packet[0] = 'Q';
    @memcpy(packet[5..][0..source.len], source);
    packet[5 + source.len] = 0;
    const length = 4 + source.len + 1;
    put32(packet[1..5], @intCast(length));
    const reply = try wire.handle(&conn, packet[0 .. 1 + length], &output);
    if (reply.blocked) return error.Blocked;
    if (reply.close) return error.ConnectionClosed;
    if (reply.consumed != 1 + length) return error.PartialFrame;
    return output[0..reply.written];
}

const Frame = struct { kind: u8, body: []const u8 };

fn nextFrame(bytes: []const u8, at: *usize) !?Frame {
    if (at.* == bytes.len) return null;
    if (bytes.len - at.* < 5) return error.TruncatedFrame;
    const length = be32(bytes[at.* + 1 ..][0..4]);
    if (length < 4 or length > bytes.len - at.* - 1) return error.TruncatedFrame;
    const frame: Frame = .{ .kind = bytes[at.*], .body = bytes[at.* + 5 .. at.* + 1 + length] };
    at.* += 1 + length;
    return frame;
}

fn zeroEnd(body: []const u8, from: usize) !usize {
    return std.mem.indexOfScalarPos(u8, body, from, 0) orelse error.MalformedFrame;
}

/// Writes `@namespace.name.kind` for an allocated type OID, read from pg_type.
fn identity(out: *Out, oid: u32) !void {
    var text: [256]u8 = undefined;
    const source = try std.fmt.bufPrint(&text, "SELECT n.nspname,t.typname,t.typtype FROM pg_catalog.pg_type t " ++
        "JOIN pg_catalog.pg_namespace n ON n.oid=t.typnamespace WHERE t.oid={d}", .{oid});
    const bytes = try query(source);
    var at: usize = 0;
    var found: ?[]const u8 = null;
    var count: usize = 0;
    while (try nextFrame(bytes, &at)) |frame| {
        if (frame.kind == 'D') {
            count += 1;
            found = frame.body;
        }
    }
    const body = found orelse return out.put("@?");
    if (count != 1 or body.len < 2 or be16(body[0..2]) != 3) return out.put("@?");
    var offset: usize = 2;
    for (0..3) |cell| {
        if (body.len - offset < 4) return error.MalformedFrame;
        const size: i32 = @bitCast(be32(body[offset..][0..4]));
        offset += 4;
        if (size < 0 or @as(usize, @intCast(size)) > body.len - offset) return out.put("@?");
        try out.put(if (cell == 0) "@" else ".");
        try out.esc(body[offset..][0..@intCast(size)]);
        offset += @intCast(size);
    }
}

/// Runs one statement and leaves its canonical head and rows in the buffers.
fn execute(source: []const u8) !void {
    const bytes = try query(source);
    var raw: Out = .{ .buf = &raw_head };
    var rows: Out = .{ .buf = &rows_text };
    row_count = 0;
    var status: u8 = 0;
    var at: usize = 0;
    // A failing statement's RowDescription and DataRows are discarded by
    // clients (libpq returns only the error); both sides drop them.
    var mark_head: usize = 0;
    var mark_rows: usize = 0;
    while (try nextFrame(bytes, &at)) |frame| {
        const body = frame.body;
        if (frame.kind == 'E') {
            raw.len = mark_head;
            row_count = mark_rows;
            rows.len = if (mark_rows == 0) 0 else row_ends[mark_rows - 1];
        }
        switch (frame.kind) {
            'T' => {
                if (raw.len != 0) try raw.byte(';');
                try raw.put("T:");
                if (body.len < 2) return error.MalformedFrame;
                var offset: usize = 2;
                for (0..be16(body[0..2])) |column| {
                    if (column != 0) try raw.byte(',');
                    const end = try zeroEnd(body, offset);
                    if (body.len - end < 19) return error.MalformedFrame;
                    try raw.esc(body[offset..end]);
                    try raw.byte('/');
                    const oid = be32(body[end + 7 ..][0..4]);
                    if (oid >= 16384) try raw.byte('#');
                    try raw.int(oid);
                    try raw.byte('/');
                    try raw.int(@as(i16, @bitCast(be16(body[end + 11 ..][0..2]))));
                    try raw.byte('/');
                    try raw.int(@as(i32, @bitCast(be32(body[end + 13 ..][0..4]))));
                    offset = end + 19;
                }
            },
            'D' => {
                if (row_count == row_ends.len) return error.CanonicalCapacity;
                if (body.len < 2) return error.MalformedFrame;
                var offset: usize = 2;
                for (0..be16(body[0..2])) |cell| {
                    if (cell != 0) try rows.byte('|');
                    if (body.len - offset < 4) return error.MalformedFrame;
                    const size: i32 = @bitCast(be32(body[offset..][0..4]));
                    offset += 4;
                    if (size < 0) {
                        try rows.put("\\N");
                    } else {
                        if (@as(usize, @intCast(size)) > body.len - offset) return error.MalformedFrame;
                        try rows.esc(body[offset..][0..@intCast(size)]);
                        offset += @intCast(size);
                    }
                }
                row_ends[row_count] = rows.len;
                row_count += 1;
            },
            'C' => {
                if (raw.len != 0) try raw.byte(';');
                try raw.put("C:");
                try raw.esc(body[0..try zeroEnd(body, 0)]);
            },
            'E' => {
                if (raw.len != 0) try raw.byte(';');
                try raw.put("E:");
                var offset: usize = 0;
                while (offset < body.len and body[offset] != 0) {
                    const end = try zeroEnd(body, offset + 1);
                    if (body[offset] == 'C') try raw.put(body[offset + 1 .. end]);
                    offset = end + 1;
                }
            },
            'I' => {
                if (raw.len != 0) try raw.byte(';');
                try raw.byte('I');
            },
            'Z' => {
                if (body.len != 1) return error.MalformedFrame;
                if (raw.len != 0) try raw.byte(';');
                try raw.put("Z:");
                try raw.byte(body[0]);
                status = body[0];
            },
            'G', 'H', 'W' => return error.UnexpectedCopy,
            else => {},
        }
        if (frame.kind == 'C' or frame.kind == 'E' or frame.kind == 'I' or frame.kind == 'Z') {
            mark_head = raw.len;
            mark_rows = row_count;
        }
    }
    if (status == 0) return error.MissingReadyForQuery;
    // Replace allocated type placeholders by their catalog identity.
    var canonical: Out = .{ .buf = &head };
    var index: usize = 0;
    const text = raw_head[0..raw.len];
    while (index < text.len) {
        if (text[index] == '\\' and index + 1 < text.len) {
            try canonical.put(text[index .. index + 2]);
            index += 2;
        } else if (text[index] == '#') {
            index += 1;
            var oid: u32 = 0;
            while (index < text.len and text[index] >= '0' and text[index] <= '9') : (index += 1) oid = oid * 10 + (text[index] - '0');
            if (status == 'E') try canonical.put("@?") else try identity(&canonical, oid);
        } else {
            try canonical.byte(text[index]);
            index += 1;
        }
    }
    head_len = canonical.len;
}

fn row(index: usize) []const u8 {
    return rows_text[if (index == 0) 0 else row_ends[index - 1]..row_ends[index]];
}

const Failure = struct { statement: usize = 0, what: []const u8 = "", wanted: []const u8 = "", got: []const u8 = "" };

fn rowsMatch(expected: []const []const u8, ordered: bool) bool {
    if (expected.len != row_count) return false;
    if (ordered) {
        for (expected, 0..) |wanted, index| {
            if (!same(wanted, row(index))) return false;
        }
        return true;
    }
    @memset(used[0..row_count], false);
    outer: for (expected) |wanted| {
        for (0..row_count) |candidate| {
            if (!used[candidate] and same(wanted, row(candidate))) {
                used[candidate] = true;
                continue :outer;
            }
        }
        return false;
    }
    return true;
}

fn runProbe(probe: *const Probe, failure: *Failure) !bool {
    store = .{};
    conn = .{ .store = &store, .id = 1 };
    wire = .{};
    try startup();
    for (probe.statements, 0..) |*statement, index| {
        failure.statement = index;
        try execute(statement.source);
        if (!same(head[0..head_len], statement.head)) {
            failure.* = .{ .statement = index, .what = "head", .wanted = statement.head, .got = head[0..head_len] };
            return false;
        }
        if (!rowsMatch(statement.rows, probe.ordered)) {
            failure.* = .{ .statement = index, .what = "rows", .wanted = if (statement.rows.len == 0) "" else statement.rows[0],
                .got = if (row_count == 0) "" else rows_text[0..row_ends[row_count - 1]] };
            return false;
        }
    }
    return true;
}

pub fn main(init: std.process.Init) !void {
    var passed: usize = 0;
    var regressions: usize = 0;
    var improved: usize = 0;
    for (&probes) |*probe| {
        var failure: Failure = .{};
        const ok = runProbe(probe, &failure) catch |err| blk: {
            failure.what = @errorName(err);
            break :blk false;
        };
        var line: Out = .{ .buf = &line_buffer };
        try line.put("{\"probe\":\"");
        try line.json(probe.id, 64);
        try line.put(if (ok) "\",\"pass\":true" else "\",\"pass\":false");
        if (!ok) {
            try line.put(",\"statement\":");
            try line.int(@intCast(failure.statement));
            try line.put(",\"what\":\"");
            try line.json(failure.what, 64);
            try line.put("\",\"wanted\":\"");
            try line.json(failure.wanted, 600);
            try line.put("\",\"got\":\"");
            try line.json(failure.got, 600);
            try line.byte('"');
        }
        try line.put("}\n");
        try std.Io.File.stdout().writeStreamingAll(init.io, line_buffer[0..line.len]);
        if (ok) {
            passed += 1;
            if (!probe.closed) improved += 1;
        } else if (probe.closed) regressions += 1;
    }
    var summary: [160]u8 = undefined;
    try std.Io.File.stdout().writeStreamingAll(init.io, try std.fmt.bufPrint(&summary,
        "{{\"suite\":\"sql-features\",\"probes\":{d},\"passed\":{d},\"improved\":{d},\"regressions\":{d}}}\n",
        .{ probes.len, passed, improved, regressions }));
    if (regressions != 0) return error.FeatureProbeRegression;
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--oracle', type=Path, default=fp.ORACLE)
    parser.add_argument('--status', type=Path, default=fp.STATUS)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    parser.add_argument('--only', action='append', help='Generate only these probe ids (development)')
    args = parser.parse_args()
    probes = fp.load_probes()
    report = json.loads(args.oracle.read_text(encoding='utf8'))
    if report.get('probes_sha256') != fp.probes_digest(probes):
        raise SystemExit('Stale feature oracle: run verify_feature_oracle.py after editing probes')
    recorded = {p['id']: p for p in report['probes']}
    passing = set()
    if args.status.exists():
        passing = set(json.loads(args.status.read_text(encoding='utf8')).get('probe_results', {}).get('pass', []))
    digest = fp.probes_digest(probes)
    out = [PRELUDE.replace('//! SQL-standard feature probes', f'//! Probes sha256: {digest}\n//!\n//! SQL-standard feature probes', 1),
           '\nconst probes = [_]Probe{\n']
    count = 0
    for probe in probes:
        if args.only and probe['id'] not in args.only:
            continue
        oracle = recorded.get(probe['id'])
        if oracle is None or not oracle['stable']:
            raise SystemExit('Unrecorded or unstable probe: ' + probe['id'])
        if len(oracle['statements']) != len(probe['statements']):
            raise SystemExit('Statement count mismatch: ' + probe['id'])
        out.append(f".{{ .id = {literal(probe['id'])}, .ordered = {str(probe['ordered']).lower()}, "
                   f".closed = {str(probe['id'] in passing).lower()}, .statements = &.{{\n")
        for source, result in zip(probe['statements'], oracle['statements']):
            rows = ', '.join(literal(r) for r in result['rows'])
            out.append(f"    .{{ .source = {literal(source)}, .head = {literal(result['head'])}, .rows = &.{{{rows}}} }},\n")
        out.append('} },\n')
        count += 1
    out.append('};\n')
    args.output.write_text(''.join(out), encoding='utf8', newline='\n')
    print(f'{count} probes -> {args.output}')


if __name__ == '__main__':
    main()
