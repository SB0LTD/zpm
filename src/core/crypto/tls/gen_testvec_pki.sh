#!/bin/bash
# Regenerate testvec_pki.sig: a small synthetic P-256 PKI used by the
# x509_verify and tls unit tests (path-validation negative cases and the
# scripted-server handshake tests). Needs OpenSSL >= 3.4 (-not_before).
#   bash src/core/crypto/tls/gen_testvec_pki.sh > src/core/crypto/tls/testvec_pki.sig
# Every certificate is valid 2026-01-01 .. 2036-01-01; tests use a fixed `now`.
set -euo pipefail
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
cd "$T"
NB=20260101000000Z
NA=20360101000000Z
serial=100

# mk NAME CN ISSUER(self|name) EXTENSIONS...
mk() {
    local name=$1 cn=$2 issuer=$3
    shift 3
    openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:P-256 -out "$name.key" 2>/dev/null
    { echo "[v3]"; printf '%s\n' "$@"; } >"$name.ext"
    openssl req -new -key "$name.key" -subj "/O=Galaxy Test PKI/CN=$cn" -out "$name.csr" 2>/dev/null
    serial=$((serial + 1))
    if [ "$issuer" = self ]; then
        openssl x509 -req -in "$name.csr" -key "$name.key" -set_serial $serial \
            -not_before $NB -not_after $NA -sha256 -extfile "$name.ext" -extensions v3 \
            -outform DER -out "$name.der" 2>/dev/null
    else
        openssl x509 -req -in "$name.csr" -CA "$issuer.pem" -CAkey "$issuer.key" -set_serial $serial \
            -not_before $NB -not_after $NA -sha256 -extfile "$name.ext" -extensions v3 \
            -outform DER -out "$name.der" 2>/dev/null
    fi
    openssl x509 -inform DER -in "$name.der" -out "$name.pem"
}

CA_EXT=("basicConstraints=critical,CA:TRUE" "keyUsage=critical,keyCertSign,cRLSign" "subjectKeyIdentifier=hash")
LEAF_EXT=("basicConstraints=critical,CA:FALSE" "keyUsage=critical,digitalSignature")

mk root "Galaxy Test Root" self "${CA_EXT[@]}"
mk inter "Galaxy Test Issuing CA" root "basicConstraints=critical,CA:TRUE,pathlen:0" \
    "keyUsage=critical,keyCertSign,cRLSign" "extendedKeyUsage=serverAuth,clientAuth"
mk leaf "tls.galaxy.test" inter "${LEAF_EXT[@]}" "extendedKeyUsage=serverAuth" \
    "subjectAltName=DNS:tls.galaxy.test,DNS:*.galaxy.test"
mk leaf_client "client.galaxy.test" inter "${LEAF_EXT[@]}" "extendedKeyUsage=clientAuth" \
    "subjectAltName=DNS:client.galaxy.test"
mk leaf_ca "ca.galaxy.test" inter "basicConstraints=critical,CA:TRUE" \
    "keyUsage=critical,digitalSignature,keyCertSign" "subjectAltName=DNS:ca.galaxy.test"
mk leaf_crit "crit.galaxy.test" inter "${LEAF_EXT[@]}" "subjectAltName=DNS:crit.galaxy.test" \
    "1.3.6.1.4.1.55555.1=critical,ASN1:NULL"
# A CA below the pathlen:0 issuing CA, and a leaf under it.
mk sub "Galaxy Test Sub CA" inter "${CA_EXT[@]}"
mk leaf_deep "deep.galaxy.test" sub "${LEAF_EXT[@]}" "subjectAltName=DNS:deep.galaxy.test"
# A CA certificate whose keyUsage does not allow certificate signing.
mk noks "Galaxy Test No-CertSign CA" root "basicConstraints=critical,CA:TRUE" \
    "keyUsage=critical,digitalSignature"
mk leaf_noks "noks.galaxy.test" noks "${LEAF_EXT[@]}" "subjectAltName=DNS:noks.galaxy.test"
# A name-constrained CA (permitted: good.test) and leaves inside and outside.
mk nc "Galaxy Test Constrained CA" root "${CA_EXT[@]}" "nameConstraints=critical,permitted;DNS:good.test"
mk leaf_nc_good "www.good.test" nc "${LEAF_EXT[@]}" "subjectAltName=DNS:www.good.test"
mk leaf_nc_bad "www.evil.test" nc "${LEAF_EXT[@]}" "subjectAltName=DNS:www.evil.test,DNS:www.good.test"

arr() { # name file
    echo "pub const $1 = [_]u8{"
    od -An -v -tx1 "$2" | tr -s ' \n' ' ' | sed 's/^ //; s/ $//' | tr ' ' '\n' |
        awk '{ printf "%s0x%s,", (NR % 16 == 1 ? "    " : " "), $1; if (NR % 16 == 0) printf "\n" } END { if (NR % 16) printf "\n" }'
    echo "};"
}

echo "// GENERATED by gen_testvec_pki.sh — synthetic P-256 test PKI (not trusted anywhere)."
echo "// Layer 1: crypto test data (internal to the tls_client directory module)."
echo "// Root -> Issuing CA (pathlen:0, EKU serverAuth+clientAuth) -> leaves; plus"
echo "// negative cases for x509_verify. Validity 2026-01-01 .. 2036-01-01."
echo
for n in root inter leaf leaf_client leaf_ca leaf_crit sub leaf_deep noks leaf_noks nc leaf_nc_good leaf_nc_bad; do
    arr "${n}_der" "$n.der"
done
# The leaf's raw P-256 private scalar (for signing CertificateVerify in tests).
openssl pkey -in leaf.key -text -noout | awk '/^pub:/ { p = 0 } p { printf "%s", $0 } /^priv:/ { p = 1 }' |
    tr -d ' :' | sed 's/^00\(.\{64\}\)$/\1/' | xxd -r -p >leaf_priv.bin
[ "$(wc -c <leaf_priv.bin | tr -d ' ')" = 32 ] || { echo "bad private key length" >&2; exit 1; }
arr leaf_priv leaf_priv.bin
