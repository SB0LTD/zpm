"""Generate src/core/unicode_class.sig from llama.cpp's unicode-data.cpp.

The BPE pre-tokenizers of the GPT-2 family split text with \\p{L}, \\p{N} and
\\s classes. Matching the reference tokenizer token-for-token needs exactly the
classification llama.cpp uses, so this script reduces its generated range
table (Unicode Character Database, via llama.cpp's scripts/gen-unicode-data.py,
MIT) to the three classes the splitters read, merges equal neighbours and
writes a bounded comptime table.

usage: python -I tools/gen_unicode_class.py <llama.cpp>/src/unicode-data.cpp > src/core/unicode_class.sig
"""

import re
import sys

LETTER = 0x0004
NUMBER = 0x0002


def parse(path):
    text = open(path, encoding="utf-8").read()
    start = text.index("unicode_ranges_flags")
    body = text[start:text.index("};", start)]
    ranges = [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}", body)]
    start = text.index("unicode_set_whitespace")
    body = text[start:text.index("};", start)]
    whitespace = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]+)", body)]
    return ranges, whitespace


def reduce(ranges):
    merged = []
    for begin, flags in ranges:
        if flags == 0:
            raise SystemExit("unexpected flag-less range at U+%06X" % begin)
        kind = 1 if flags & LETTER else 2 if flags & NUMBER else 0
        if merged and merged[-1][1] == kind:
            continue
        merged.append((begin, kind))
    return merged


def main():
    sys.stdout.reconfigure(newline="\n")  # LF on every host
    ranges, whitespace = parse(sys.argv[1])
    if ranges[0][0] != 0 or ranges[-1][0] != 0x110000:
        raise SystemExit("unexpected range table bounds")
    merged = reduce(ranges[:-1])
    out = sys.stdout
    out.write("//! Unicode letter/number/whitespace classes for BPE pre-tokenizers.\n")
    out.write("//!\n")
    out.write("//! GENERATED by tools/gen_unicode_class.py from llama.cpp's unicode-data.cpp\n")
    out.write("//! (Unicode Character Database, MIT). Do not edit by hand. Each entry packs\n")
    out.write("//! `first_codepoint << 2 | class` and holds until the next entry.\n\n")
    out.write("pub const Class = enum(u2) { other = 0, letter = 1, number = 2 };\n\n")
    out.write("pub const MAX_CODEPOINT: u32 = 0x10ffff;\n\n")
    out.write("/// Class of a scalar value. Values past MAX_CODEPOINT are `other`.\n")
    out.write("pub fn classify(codepoint: u32) Class {\n")
    out.write("    if (codepoint > MAX_CODEPOINT) return .other;\n")
    out.write("    var low: usize = 0;\n")
    out.write("    var high: usize = ranges.len;\n")
    out.write("    while (high - low > 1) {\n")
    out.write("        const middle = low + (high - low) / 2;\n")
    out.write("        if (ranges[middle] >> 2 <= codepoint) low = middle else high = middle;\n")
    out.write("    }\n")
    out.write("    return @enumFromInt(@as(u2, @truncate(ranges[low])));\n")
    out.write("}\n\n")
    out.write("/// The `\\s` set of the reference regex engine.\n")
    out.write("pub fn isWhitespace(codepoint: u32) bool {\n")
    out.write("    for (whitespace) |value| if (value == codepoint) return true;\n")
    out.write("    return false;\n")
    out.write("}\n\n")
    out.write("const whitespace = [_]u32{\n")
    for index in range(0, len(whitespace), 8):
        out.write("    " + ", ".join("0x%04x" % v for v in whitespace[index:index + 8]) + ",\n")
    out.write("};\n\n")
    out.write("const ranges = [_]u32{\n")
    for index in range(0, len(merged), 6):
        out.write("    " + ", ".join("0x%06x << 2 | %d" % item for item in merged[index:index + 6]) + ",\n")
    out.write("};\n\n")
    out.write('test "ASCII classes" {\n')
    out.write("    if (classify('a') != .letter or classify('Z') != .letter) return error.TestUnexpectedResult;\n")
    out.write("    if (classify('7') != .number or classify('-') != .other) return error.TestUnexpectedResult;\n")
    out.write("    if (!isWhitespace(' ') or !isWhitespace('\\n') or isWhitespace('x')) return error.TestUnexpectedResult;\n")
    out.write("}\n\n")
    out.write('test "non-ASCII classes" {\n')
    out.write("    if (classify(0x00e9) != .letter or classify(0x4e2d) != .letter) return error.TestUnexpectedResult;\n")
    out.write("    if (classify(0x0663) != .number or classify(0x00b2) != .number) return error.TestUnexpectedResult;\n")
    out.write("    if (classify(0x0301) != .other or classify(0x3002) != .other) return error.TestUnexpectedResult;\n")
    out.write("    if (!isWhitespace(0x3000) or isWhitespace(0x00e9)) return error.TestUnexpectedResult;\n")
    out.write("}\n")


if __name__ == "__main__":
    main()
