#!/usr/bin/env python3
"""src/nvidia/sm120_latency.sig from NVIDIA's latency tables as Mesa ships
them (src/nouveau/compiler/latencies/sm100/*.csv, MIT license; NAK uses the
sm_100 tables for sm_120 too).

Dev only: the generated file is checked in.

    python tools/gen_sm120_latencies.py MESA_LATENCIES_SM100_DIR MESA_COMMIT

Each CSV is a square table: its first row names the categories, then one
row per category. The row is the second instruction of the pair (the reader
of a RAW, the writer of a WAR, the second writer of a WAW), the column the
first. An entry is cycles, "N & sb" (a scoreboard, and N cycles), "A+B" (A
cycles, B more when the first instruction is predicated: the sum is kept,
the predicated case, to be safe) or none (no such pair).
"""

import csv
import os
import sys

FILES = ["reg", "pred", "ureg"]
KINDS = ["raw", "war", "waw"]


def read(path):
    rows = [r for r in csv.reader(open(path)) if r and not r[0].startswith("#")]
    cats = [c.strip() for c in rows[0][1:]]
    table = {}
    for r in rows[1:]:
        table[r[0].strip()] = {c: v.strip() for c, v in zip(cats, r[1:])}
    return cats, table


def entry(v):
    if v == "none":
        return "N"
    sb = v.endswith("& sb")
    v = v.replace("& sb", "").strip()
    n = sum(int(x) for x in v.split("+"))
    assert n < 0x80
    return f"0x{n | (0x80 if sb else 0):02x}"


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    d, commit = sys.argv[1], sys.argv[2]
    out = [
        "//! sm_120 instruction latencies: NVIDIA's tables for sm_100, as Mesa's NAK",
        "//! compiler ships them (src/nouveau/compiler/latencies/sm100/*.csv, MIT",
        "//! license, Copyright Red Hat; Mesa commit " + commit[:12] + "), which NAK uses for",
        "//! sm_120 too. Generated by tools/gen_sm120_latencies.py: do not edit.",
        "//!",
        "//! A table is indexed [second][first]: the second instruction of the pair",
        "//! (a RAW's reader, a WAR's writer, a WAW's second writer), then the first.",
        "//! An entry is cycles, with SB set when the pair needs a scoreboard (and",
        "//! then at least that many cycles too), or N when NVIDIA gives none. Where",
        "//! a table has a predicated case (A+B: B more cycles when the first",
        "//! instruction has a predicate) the sum is kept.",
        "",
        "pub const N: u8 = 0xff;",
        "pub const SB: u8 = 0x80;",
        "",
    ]
    for f in FILES:
        cats = None
        tables = {}
        for k in KINDS:
            c, t = read(os.path.join(d, f"{f}_{k}.csv"))
            if cats is None:
                cats = c
            assert c == cats, f"{f}_{k}: categories differ"
            tables[k] = t
        enum = {"reg": "Reg", "pred": "Pred", "ureg": "Ureg"}[f]
        out.append(f"/// The {'general' if f == 'reg' else 'predicate' if f == 'pred' else 'uniform'} register file's latency categories.")
        out.append(f"pub const {enum} = enum(u8) {{")
        for c in cats:
            out.append(f"    {c},")
        out.append("};")
        out.append("")
        for k in KINDS:
            out.append(f"pub const {f}_{k} = [{len(cats)}][{len(cats)}]u8{{")
            for row in cats:
                vals = ", ".join(entry(tables[k][row][col]) for col in cats)
                out.append(f"    .{{ {vals} }}, // {row}")
            out.append("};")
            out.append("")
    path = os.path.join(os.path.dirname(__file__), "..", "src", "nvidia", "sm120_latency.sig")
    with open(path, "w", newline="\n") as fh:
        fh.write("\n".join(out))
    print(path)


if __name__ == "__main__":
    main()
