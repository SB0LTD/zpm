#!/usr/bin/env python3
"""Generate src/core/sql/unicode_tables.sig from the Unicode Character Database.

PostgreSQL 18 normalizes with Unicode 16.0 (src/include/common/unicode_version.h).
Inputs: UnicodeData.txt and DerivedNormalizationProps.txt of that version, from
https://www.unicode.org/Public/16.0.0/ucd/. The output holds canonical combining
classes, single-level decomposition mappings and the primary composites
(canonical pairs that are not Full_Composition_Exclusion); Hangul syllables are
algorithmic in functions_unicode.sig. Entries are packed u64 values.

usage: gen_unicode_normalization.py <ucd-dir> <output.sig>
"""
import sys
from pathlib import Path


def rows(values, per_line, width):
    lines = []
    for index in range(0, len(values), per_line):
        chunk = values[index:index + per_line]
        lines.append('    ' + ', '.join(f'0x{v:0{width}X}' for v in chunk) + ',\n')
    return lines


def main():
    ucd = Path(sys.argv[1])
    output = Path(sys.argv[2])
    classes = {}
    decompositions = {}
    for line in (ucd / 'UnicodeData.txt').read_text(encoding='utf8').splitlines():
        fields = line.split(';')
        code = int(fields[0], 16)
        if int(fields[3]) != 0:
            classes[code] = int(fields[3])
        if fields[5]:
            parts = fields[5].split()
            compat = parts[0].startswith('<')
            if compat:
                parts = parts[1:]
            decompositions[code] = (compat, [int(p, 16) for p in parts])
    exclusions = set()
    for line in (ucd / 'DerivedNormalizationProps.txt').read_text(encoding='utf8').splitlines():
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        codes, prop = [p.strip() for p in line.split(';')[:2]]
        if prop != 'Full_Composition_Exclusion':
            continue
        if '..' in codes:
            first, last = codes.split('..')
            exclusions.update(range(int(first, 16), int(last, 16) + 1))
        else:
            exclusions.add(int(codes, 16))
    ranges = []
    for code in sorted(classes):
        value = classes[code]
        if ranges and ranges[-1][1] == code - 1 and ranges[-1][2] == value:
            ranges[-1][1] = code
        else:
            ranges.append([code, code, value])
    mapping = []
    entries = []
    for code in sorted(decompositions):
        compat, parts = decompositions[code]
        entries.append((code, compat, len(mapping), len(parts)))
        mapping.extend(parts)
    compositions = []
    for code, (compat, parts) in decompositions.items():
        if compat or len(parts) != 2 or code in exclusions:
            continue
        compositions.append((parts[0], parts[1], code))
    compositions.sort()
    out = ['//! Generated by tools/gen_unicode_normalization.py from the Unicode 16.0.0\n',
           '//! UCD (UnicodeData.txt, DerivedNormalizationProps.txt). Do not edit.\n',
           '//! Packed entries, sorted by their leading field:\n',
           '//! combining: first << 29 | last << 8 | class;\n',
           '//! decompositions: code << 22 | compat << 21 | start << 5 | len;\n',
           '//! compositions: first << 42 | second << 21 | composite.\n',
           'pub const version = "16.0.0";\n\n',
           'pub const combining = [_]u64{\n']
    out += rows([(f << 29) | (last << 8) | c for f, last, c in ranges], 8, 13)
    out.append('};\n\npub const decompositions = [_]u64{\n')
    out += rows([(code << 22) | (int(compat) << 21) | (start << 5) | length for code, compat, start, length in entries], 8, 11)
    out.append('};\n\npub const mapping = [_]u21{\n')
    out += rows(mapping, 12, 4)
    out.append('};\n\npub const compositions = [_]u64{\n')
    out += rows([(f << 42) | (second << 21) | c for f, second, c in compositions], 6, 16)
    out.append('};\n')
    output.write_text(''.join(out), encoding='utf8', newline='\n')
    print(f'{len(ranges)} class ranges, {len(entries)} decompositions, {len(mapping)} mapped, {len(compositions)} compositions')


if __name__ == '__main__':
    main()
