#!/usr/bin/env python3
"""Generate src/core/sql/information_schema_data.sig from native PostgreSQL 18.

Reads, from a trust-auth native PostgreSQL 18 server (default 127.0.0.1:55491,
user postgres, database postgres):

  * every information_schema relation's columns in attnum order, each typed by
    its information_schema domain (sql_identifier, cardinal_number,
    character_data, yes_or_no, time_stamp);
  * the rows of sql_features, sql_implementation_info, sql_parts and sql_sizing
    in physical order, cells separated by `|` and NULL written `\\N`.

The internal _pg_* helper views use plain oid, name and text[] columns.
Stdlib only; uses the wire client of
tests/sql_conformance/verify_feature_oracle.py.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tests' / 'sql_conformance'))
import verify_feature_oracle as oracle  # noqa: E402

DOMAINS = {
    'sql_identifier': 'id',
    'cardinal_number': 'number',
    'character_data': 'chars',
    'yes_or_no': 'yes_no',
    'time_stamp': 'stamp',
    # Plain types of the internal _pg_* helper views.
    'oid': 'oid',
    '_text': 'text_array',
    'name': 'name',
}

COLUMNS_SQL = """
SELECT c.relname, c.relkind, a.attname, t.typname
FROM pg_catalog.pg_class c
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
JOIN pg_catalog.pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
JOIN pg_catalog.pg_type t ON t.oid = a.atttypid
WHERE n.nspname = 'information_schema'
ORDER BY c.relname, a.attnum
"""

TABLES = ('sql_features', 'sql_implementation_info', 'sql_parts', 'sql_sizing')


def sig_string(lines):
    out = []
    for line in lines:
        out.append('    \\\\' + line)
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--port', type=int, default=55491)
    parser.add_argument('--user', default='postgres')
    parser.add_argument('--database', default='postgres')
    parser.add_argument('--output', type=Path, default=ROOT / 'src' / 'core' / 'sql' / 'information_schema_data.sig')
    args = parser.parse_args()
    session = oracle.Session(args.port, args.user, args.database, timezone=None)
    try:
        version = session.rows('SHOW server_version_num')[0][0].decode()
        if not version.startswith('18'):
            raise SystemExit('information_schema is generated from PostgreSQL 18')
        relations = {}
        kinds = {}
        for relname, relkind, attname, typname in session.rows(COLUMNS_SQL):
            name = relname.decode()
            kinds[name] = relkind.decode()
            domain = DOMAINS[typname.decode()]
            relations.setdefault(name, []).append((attname.decode(), domain))
        data = {}
        for table in TABLES:
            rows = []
            for row in session.rows(f'SELECT * FROM information_schema.{table}'):
                cells = []
                for cell in row:
                    if cell is None:
                        cells.append('\\N')
                    else:
                        text = cell.decode()
                        if '|' in text or '\n' in text or '\\' in text:
                            raise SystemExit(f'{table}: unexpected byte in {text!r}')
                        cells.append(text)
                rows.append('|'.join(cells))
            data[table] = rows
    finally:
        session.close()

    out = []
    out.append('//! GENERATED by tools/gen_information_schema.py from native PostgreSQL 18.7.')
    out.append('//! Do not edit by hand.')
    out.append('//!')
    out.append('//! Column shapes of every information_schema relation (attnum order,')
    out.append('//! information_schema domain of each column) and the rows of the four')
    out.append('//! information_schema tables in physical order: `|`-separated cells,')
    out.append('//! `\\N` for NULL. Names are offsets into one text so no constant holds')
    out.append('//! slices (native SB0 backend).')
    out.append('')
    out.append('/// The information_schema domain of a column, or (oid, text_array,')
    out.append('/// name) the plain type of a _pg_* helper view column.')
    out.append('pub const Domain = enum(u8) { id, number, chars, yes_no, stamp, oid, text_array, name };')
    out.append('')
    out.append('/// A relation: its name, \'r\' (table) or \'v\' (view), and its columns')
    out.append('/// `columns[first .. first + count]`.')
    out.append('pub const Relation = struct { name_start: u16, name_len: u8, kind: u8, first: u16, count: u8 };')
    out.append('pub const Column = struct { name_start: u16, name_len: u8, domain: Domain };')
    out.append('')
    names = []
    offsets = {}

    def intern(text):
        if text in offsets:
            return offsets[text]
        start = sum(len(n) for n in names)
        names.append(text)
        offsets[text] = start
        return start

    relation_lines = []
    column_lines = []
    first = 0
    for name in sorted(relations):
        start = intern(name)
        columns = relations[name]
        relation_lines.append(f'    .{{ .name_start = {start}, .name_len = {len(name)}, .kind = \'{kinds[name]}\', .first = {first}, .count = {len(columns)} }}, // {name}')
        for column, domain in columns:
            column_lines.append(f'    .{{ .name_start = {intern(column)}, .name_len = {len(column)}, .domain = .{domain} }}, // {name}.{column}')
        first += len(columns)
    text = ''.join(names)
    out.append('pub const names = ' + '"' + text + '";')
    out.append('')
    out.append('/// In relation-name order.')
    out.append('pub const relations = [_]Relation{')
    out.extend(relation_lines)
    out.append('};')
    out.append('')
    out.append('pub const columns = [_]Column{')
    out.extend(column_lines)
    out.append('};')
    for table in TABLES:
        out.append('')
        out.append(f'/// information_schema.{table}, physical order.')
        out.append(f'pub const {table} =')
        out.append(sig_string(data[table]))
        out.append(';')
    out.append('')
    args.output.write_text('\n'.join(out), encoding='utf8', newline='\n')
    print(f'wrote {args.output}: {len(relations)} relations, {first} columns')


if __name__ == '__main__':
    main()
