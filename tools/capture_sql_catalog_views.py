#!/usr/bin/env python3
"""Record native PostgreSQL 18 results of the catalog-views contract scripts.

Each script in tests/sql_conformance/catalog_views/*.sql runs on a fresh
database (`catalog_views_probe`, created from template0) through one
simple-query session with TimeZone=UTC, one statement per Query message,
continuing after errors. Every response is reduced to the canonical form of
tests/sql_conformance/feature_probes.py (message order, RowDescription
name/type/typlen/typmod, command tags, SQLSTATEs, ReadyForQuery status and
DataRow text). Roles named `w5c_*` that a script creates are dropped after it.

ZPM's bootstrap superuser is `ramsql` where the oracle connects as
`postgres`: a DataRow cell that is exactly the oracle user's name is
rewritten to `ramsql`. Nothing else is changed.

Writes tests/test_sql_catalog_views_cases.sig. Development tool; Python
stdlib only (the wire client of verify_feature_oracle.py).
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tests' / 'sql_conformance'))
import feature_probes as fp  # noqa: E402
import verify_feature_oracle as oracle  # noqa: E402

SCRIPTS = ROOT / 'tests' / 'sql_conformance' / 'catalog_views'
OUTPUT = ROOT / 'tests' / 'test_sql_catalog_views_cases.sig'
PROBE_DB = 'catalog_views_probe'


def statements(text):
    out, current = [], []
    for line in text.splitlines():
        line = line.rstrip()
        if not current and (not line.strip() or line.strip().startswith('--')):
            continue
        current.append(line)
        joined = '\n'.join(current)
        if line.endswith(';') and fp._dollar_balanced(joined):
            out.append(joined[:-1])
            current = []
    if current:
        raise SystemExit('unterminated statement: ' + '\n'.join(current))
    return out


def split_cells(row):
    cells, current, escaped = [], '', False
    for char in row:
        if escaped:
            current += char
            escaped = False
        elif char == '\\':
            current += char
            escaped = True
        elif char == '|':
            cells.append(current)
            current = ''
        else:
            current += char
    cells.append(current)
    return cells


def sig_string(value):
    out = ['"']
    for byte in value.encode('utf8'):
        if byte in (0x22, 0x5c):
            out.append('\\' + chr(byte))
        elif byte < 0x20 or byte >= 0x7f:
            out.append('\\x%02x' % byte)
        else:
            out.append(chr(byte))
    out.append('"')
    return ''.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--port', type=int, default=55491)
    parser.add_argument('--user', default='postgres')
    parser.add_argument('--admin-database', default='postgres')
    args = parser.parse_args()
    admin = oracle.Session(args.port, args.user, args.admin_database, timezone=None)
    version = admin.rows('SELECT version()')[0][0].decode()
    if not admin.rows('SHOW server_version_num')[0][0].decode().startswith('18'):
        raise SystemExit('the catalog views are recorded against PostgreSQL 18')

    def cleanup():
        admin.raw(f'DROP DATABASE IF EXISTS {PROBE_DB} WITH (FORCE)')
        for (name,) in admin.rows("SELECT rolname FROM pg_catalog.pg_roles WHERE rolname LIKE 'w5c\\_%'"):
            admin.raw('DROP ROLE ' + name.decode())

    scripts = []
    try:
        for path in sorted(SCRIPTS.glob('*.sql')):
            cleanup()
            admin.raw(f'CREATE DATABASE {PROBE_DB} TEMPLATE template0')
            session = oracle.Session(args.port, args.user, PROBE_DB)
            recorded = []
            try:
                for source in statements(path.read_text(encoding='utf8')):
                    result = session.canonical(source)
                    rows = []
                    for row in result['rows']:
                        rows.append('|'.join('ramsql' if cell == args.user else cell for cell in split_cells(row)))
                    ordered = re.search(r'\bORDER BY\b', source) is not None
                    recorded.append((source, result['head'], rows, ordered))
            finally:
                session.close()
            scripts.append((path.stem, recorded))
            print(path.name, len(recorded), 'statements', flush=True)
    finally:
        cleanup()
        admin.close()

    out = []
    out.append('//! GENERATED by tools/capture_sql_catalog_views.py from')
    out.append('//! tests/sql_conformance/catalog_views/*.sql against ' + version.split(' (')[0] + '.')
    out.append('//! Do not edit by hand. The oracle user `postgres` is ZPM\'s `ramsql`.')
    out.append('pub const Statement = struct { source: []const u8, head: []const u8, rows: []const []const u8, ordered: bool };')
    out.append('pub const Script = struct { name: []const u8, statements: []const Statement };')
    out.append('pub const database = ' + sig_string(PROBE_DB) + ';')
    out.append('pub const scripts = [_]Script{')
    for name, recorded in scripts:
        out.append('    .{ .name = ' + sig_string(name) + ', .statements = &.{')
        for source, head, rows, ordered in recorded:
            row_text = ', '.join(sig_string(row) for row in rows)
            out.append('        .{ .source = ' + sig_string(source) + ', .head = ' + sig_string(head) +
                       ', .rows = &.{' + row_text + '}, .ordered = ' + ('true' if ordered else 'false') + ' },')
        out.append('    } },')
    out.append('};')
    OUTPUT.write_text('\n'.join(out) + '\n', encoding='utf8', newline='\n')
    print('wrote', OUTPUT)


if __name__ == '__main__':
    main()
